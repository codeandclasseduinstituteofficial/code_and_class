import mongoose from "mongoose";

const supporterSchema = new mongoose.Schema(
  {
    imgLink: {
      type: String,
      required: true,
      trim: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    designation: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      required: true,
      trim: true,
    },
  },
  {
    timestamps: true,
  }
);

const Supporter = mongoose.model("Supporter", supporterSchema);

export default Supporter;